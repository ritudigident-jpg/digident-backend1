// Writes docs/ENDPOINTS.md: every route with its method, full path and middleware chain, read
// statically from src/app.js and src/routes/*. Run after changing routes: npm run endpoints
// Review the diff: a URL, method or middleware change must be intended.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url); // acorn is installed with eslint
const acorn = require("acorn");

const parse = (file) =>
  acorn.parse(fs.readFileSync(file, "utf8"), {
    ecmaVersion: "latest",
    sourceType: "module",
    locations: true,
  });
const src = (file, node) => fs.readFileSync(file, "utf8").slice(node.start, node.end).replace(/\s+/g, " ");
const METHODS = ["get", "post", "put", "patch", "delete", "all"];

function importsOf(file, ast) {
  const map = {};
  for (const node of ast.body)
    if (node.type === "ImportDeclaration" && node.source.value.startsWith(".")) {
      const target = path.resolve(path.dirname(file), node.source.value);
      for (const spec of node.specifiers)
        if (spec.type === "ImportDefaultSpecifier") map[spec.local.name] = target;
    }
  return map;
}

// Walk every statement-level call `x.method(...)` in a file, in order.
function calls(ast) {
  const out = [];
  const visit = (node) => {
    if (!node || typeof node !== "object") return;
    if (node.type === "ExpressionStatement" && node.expression.type === "CallExpression") {
      let call = node.expression;
      // router.route("/x").get(a).post(b)
      const chain = [];
      while (call.type === "CallExpression" && call.callee.type === "MemberExpression") {
        chain.unshift({ method: call.callee.property.name, args: call.arguments });
        call = call.callee.object;
      }
      if (call.type === "Identifier") out.push({ object: call.name, chain });
      return;
    }
    for (const key of ["body", "consequent"])
      if (Array.isArray(node[key])) node[key].forEach(visit);
      else if (node[key]?.body) visit(node[key]);
  };
  ast.body.forEach(visit);
  return out;
}

function routesOf(file, prefix, inherited, seen = new Set()) {
  if (seen.has(file)) return [];
  seen.add(file);
  const ast = parse(file);
  const imports = importsOf(file, ast);
  const result = [];
  let shared = [...inherited];
  for (const { object, chain } of calls(ast)) {
    if (!["router", "app"].includes(object) && !/Router$/i.test(object)) continue;
    let base = "";
    for (const link of chain) {
      if (link.method === "route") {
        base = link.args[0]?.value ?? "";
        continue;
      }
      if (link.method === "use") {
        const [first, ...rest] = link.args;
        const hasPath = first?.type === "Literal";
        const mountPath = hasPath ? first.value : "";
        const parts = hasPath ? rest : link.args;
        const last = parts.at(-1);
        if (
          last?.type === "Identifier" &&
          imports[last.name] &&
          fs.existsSync(`${imports[last.name]}`) &&
          /routes?\//.test(imports[last.name])
        ) {
          const mids = parts.slice(0, -1).map((a) => src(file, a));
          result.push(...routesOf(imports[last.name], prefix + mountPath, [...shared, ...mids], seen));
        } else if (!hasPath) {
          if (object !== "app") shared = [...shared, ...parts.map((a) => src(file, a))];
        } else
          result.push({
            method: "USE",
            path: prefix + mountPath,
            chain: [...shared, ...parts.map((a) => src(file, a))].join(" -> "),
            file,
          });
        continue;
      }
      if (!METHODS.includes(link.method)) continue;
      const args = base ? link.args : link.args.slice(1);
      const routePath = base || link.args[0]?.value || src(file, link.args[0]);
      result.push({
        method: link.method.toUpperCase(),
        path: (prefix + routePath).replace(/\/+$/, "") || "/",
        chain: [...shared, ...args.map((a) => src(file, a))].join(" -> "),
        file: path.relative(process.cwd(), file),
      });
    }
  }
  return result;
}

const all = routesOf(path.resolve("src/app.js"), "", []).filter((r) => r.method !== "USE");
const lines = [
  "# Endpoints",
  "",
  `${all.length} endpoints. Generated by scripts/endpoints.mjs from the route files; do not edit by hand. App-wide middleware (security headers, CORS, logging, rate limits) is listed in src/app.js and not repeated here.`,
  "",
  "| Method | Path | Middleware chain -> handler | Route file |",
  "|---|---|---|---|",
];
for (const r of all)
  lines.push(`| ${r.method} | \`${r.path}\` | \`${r.chain.replace(/\|/g, "\\|")}\` | ${r.file} |`);
const out = process.argv[2];
if (out) fs.writeFileSync(out, `${lines.join("\n")}\n`);
console.log(`${all.length} endpoints`);
